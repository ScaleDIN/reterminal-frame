#!/usr/bin/env python3
"""Builds a device's web page from the kit and embeds it in firmware as gzipped PROGMEM bytes.

    python embed_ui.py --ui <project>/ui --out <project>/src/web_page.h [--html build/ui/index.html]

<ui> holds the device's part of the page:
    body.html   page markup (start from kit/skeleton-body.html)
    device.js   page logic (uses window.K: core.js + chart.js)
    kit/        vendored copy of the kit (css, js, template, VERSION); falls back to the kit next to this script
The <title> is taken from the first <h1> in body.html.
"""
import argparse
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_FILES_JS = ["core.js", "chart.js"]


def find_kit(ui):
    for d in (os.path.join(ui, "kit"), os.path.join(HERE, "..", "kit")):
        if os.path.isfile(os.path.join(d, "template.html")):
            return os.path.normpath(d)
    sys.exit("kit not found (expected <ui>/kit or the skill's kit folder)")


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def strip_css(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return "\n".join(l.strip() for l in s.splitlines() if l.strip())


def strip_js(s):
    # Conservative: drop whole-line // comments and leading indentation only (strings stay untouched).
    out = []
    in_block = False
    for line in s.splitlines():
        t = line.strip()
        if in_block:
            if "*/" in t:
                in_block = False
            continue
        if t.startswith("/*") and "*/" not in t:
            in_block = True
            continue
        if t.startswith("/*") and t.endswith("*/"):
            continue
        if not t or t.startswith("//"):
            continue
        out.append(t)
    return "\n".join(out)


def build_html(ui):
    kit = find_kit(ui)
    body = read(os.path.join(ui, "body.html"))
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    m = re.search(r"<h1[^>]*>(.*?)</h1>", body, re.S)
    title = re.sub(r"<[^>]+>", "", m.group(1)).strip() if m else "Device"
    css = strip_css(read(os.path.join(kit, "base.css")))
    extra_css = os.path.join(ui, "device.css")
    if os.path.isfile(extra_css):
        css += "\n" + strip_css(read(extra_css))
    kit_js = "\n".join(strip_js(read(os.path.join(kit, f))) for f in KIT_FILES_JS)
    dev_js = strip_js(read(os.path.join(ui, "device.js")))
    html = read(os.path.join(kit, "template.html"))
    for k, v in (("__TITLE__", title), ("__CSS__", css), ("__BODY__", body.strip()),
                 ("__KIT_JS__", kit_js), ("__DEVICE_JS__", dev_js)):
        html = html.replace(k, v)
    version = read(os.path.join(kit, "VERSION")).strip()
    return html, version


def write_header(html, version, out):
    gz = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    text = (f"// Generated by embed_ui.py (device-web-ui kit v{version}) from ui/. Do not edit: edit ui/ and rebuild.\n"
            "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n#include <pgmspace.h>\n\n"
            f"#define WEB_PAGE_KIT_VERSION {version}\n"
            f"static const size_t WEB_PAGE_GZ_LEN = {len(gz)};  // {len(html)} bytes uncompressed\n"
            "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return len(gz)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ui", required=True)
    ap.add_argument("--out", required=True, help="generated C header")
    ap.add_argument("--html", help="also write the plain page here (for review)")
    a = ap.parse_args()
    html, version = build_html(a.ui)
    n = write_header(html, version, a.out)
    if a.html:
        os.makedirs(os.path.dirname(os.path.abspath(a.html)), exist_ok=True)
        with open(a.html, "w", encoding="utf-8", newline="\n") as f:
            f.write(html)
    print(f"{a.out}: {len(html)} bytes -> {n} gzipped (kit v{version})")


if __name__ == "__main__":
    main()
